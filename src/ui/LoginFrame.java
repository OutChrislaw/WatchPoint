    public void handleLogin() {
        String loginId = usernameField.getText().trim();
        String password = new String(passwordField.getPassword());

        if (loginId.length() == 0 || password.length() == 0) {
            showMessage("Please enter your username or ID and password.");
            return;
        }

        User user = userManager.login(loginId, password);

        if (user == null) {
            showMessage("Invalid username, ID or password.");
            return;
        }

        if (user.getUserType().equals("Administrator")) {
            AdminDashboard dashboard = new AdminDashboard((Administrator) user, reportManager, userManager,
                    locationManager);
            dashboard.setVisible(true);
        } else if (user.getUserType().equals("AreaOfficer")) {
            AreaOfficerDashboard dashboard = new AreaOfficerDashboard((AreaOfficer) user, reportManager,
                    userManager, locationManager);
            dashboard.setVisible(true);
        } else {
            ResidentDashboard dashboard = new ResidentDashboard((Resident) user, reportManager, userManager,
                    locationManager);
            dashboard.setVisible(true);
        }

        this.dispose();
    }

    public void openRegistration() {
        RegistrationFrame registrationFrame = new RegistrationFrame(userManager, locationManager);
        registrationFrame.setLocationRelativeTo(this);
        registrationFrame.addWindowListener(new java.awt.event.WindowAdapter() {
            @Override
            public void windowClosed(java.awt.event.WindowEvent event) {
                LoginFrame.this.toFront();
                LoginFrame.this.requestFocus();
            }
        });
        registrationFrame.setVisible(true);
    }

